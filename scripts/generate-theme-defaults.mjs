/**
 * One-off generator for the flowbite-react exit.
 *
 * Writes ui/theme-defaults.ts: the class strings flowbite-react RESOLVES at
 * runtime for each component we own — its default theme deep-merged (via
 * tailwind-merge) with our customTheme, under the same store settings the apps
 * run with (dark: true, prefix: "", version: 4 — see each app's
 * .flowbite-react/config.json). Core's theme/flowbite-theme.ts is only the
 * override layer; copying it as defaults would drop everything the base
 * supplies (rounded corners, sizes, disabled styles).
 *
 * Run: npm i --no-save flowbite-react@0.12.17 && node scripts/generate-theme-defaults.mjs
 * flowbite-react is no longer a dependency of any kind; this script and
 * theme/flowbite-theme.ts go in the exit's final step.
 */
import { resolveTheme } from 'flowbite-react/helpers/resolve-theme'
import { setStore } from 'flowbite-react/store'
import { theme } from 'flowbite-react/theme'
import { writeFileSync } from 'node:fs'
import { customTheme } from '../theme/flowbite-theme.ts'

setStore({ dark: true, prefix: '', version: 4 })

// Components the owned UI layer provides (flowbite-react theme keys).
const OWNED = [
  'alert',
  'badge',
  'breadcrumb',
  'button',
  'card',
  'checkbox',
  'darkThemeToggle',
  'dropdown',
  'fileInput',
  'helperText',
  'label',
  'modal',
  'navbar',
  'progress',
  'radio',
  'select',
  'sidebar',
  'spinner',
  'table',
  'tabs',
  'textarea',
  'textInput',
  'toast',
  'toggleSwitch',
  'tooltip',
]

const resolved = resolveTheme([theme, customTheme])
const out = {}
for (const key of OWNED) {
  if (!(key in resolved)) throw new Error(`theme key missing upstream: ${key}`)
  out[key] = resolved[key]
}
const missingCustom = Object.keys(customTheme).filter((k) => !OWNED.includes(k))
if (missingCustom.length)
  console.warn('customTheme keys not in OWNED:', missingCustom.join(', '))

const body = JSON.stringify(out, null, 2).replace(
  /"([a-zA-Z_][a-zA-Z0-9_]*)":/g,
  '$1:'
)
writeFileSync(
  'ui/theme-defaults.ts',
  `// GENERATED by scripts/generate-theme-defaults.mjs — do not edit by hand.\n` +
    `// flowbite-react 0.12.17 default theme deep-merged with theme/flowbite-theme.ts,\n` +
    `// resolved with { dark: true, prefix: "", version: 4 }. Class strings are MIT,\n` +
    `// Copyright (c) 2022 Themesberg (flowbite-react).\n\n` +
    `export const themeDefaults = ${body} as const\n\n` +
    `export type ThemeDefaults = typeof themeDefaults\n`
)
console.log(
  `wrote ui/theme-defaults.ts with ${Object.keys(out).length} components`
)
